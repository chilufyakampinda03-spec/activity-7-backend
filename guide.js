// Builds the HTML API guide shown at GET /
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

module.exports = function guide(baseUrl) {
  const project = esc(process.env.PROJECT_NAME || "Library Service Requests");
  const student = esc(process.env.STUDENT_NAME || "Your Name");
  const number = esc(process.env.STUDENT_NUMBER || "202407715");
  const description = esc(
    process.env.SYSTEM_DESCRIPTION ||
      "Students log and track library requests for book searches, borrowing support and account help."
  );
  const base = esc(baseUrl);
  const sample = JSON.stringify(
    {
      title: "Extend loan on networking textbook",
      category: "Borrowing",
      description: "Requesting a seven-day renewal before the due date.",
      status: "Pending",
    },
    null,
    2
  );
  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${project} - API Guide</title>
<style>
 body{font-family:system-ui,Arial,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem;line-height:1.5;color:#1f2933}
 h1{margin-bottom:.2rem} h2{margin-top:2rem;border-bottom:2px solid #d9e2ec;padding-bottom:.2rem}
 table{border-collapse:collapse;width:100%;margin:.5rem 0} th,td{border:1px solid #cbd2d9;padding:.45rem .6rem;text-align:left;vertical-align:top}
 th{background:#e4eef8} code,pre{background:#f0f4f8;border-radius:4px} code{padding:.1rem .3rem} pre{padding:.8rem;overflow-x:auto}
 .note{background:#fff8e1;border-left:4px solid #f5b400;padding:.6rem .9rem}
</style></head><body>
<h1>${project}</h1>
<p><strong>${student}</strong> &middot; Student number: <strong>${number}</strong> &middot; ICT251 Activity 7</p>
<p>${description}</p>
<p>Live API base URL: <a href="${base}">${base}</a></p>
<p>Quick links: <a href="/health">/health</a> &middot; <a href="/api/records">/api/records</a></p>
<p class="note">This service may be idle on a free plan. The first request after a pause can take up to a minute while it starts.</p>

<h2>Routes</h2>
<table><tr><th>Method</th><th>Route</th><th>Purpose</th></tr>
<tr><td>GET</td><td>/</td><td>This API guide</td></tr>
<tr><td>GET</td><td>/health</td><td>Check that the server and database respond</td></tr>
<tr><td>GET</td><td>/api/records</td><td>Read all records</td></tr>
<tr><td>GET</td><td>/api/records/:id</td><td>Read one record</td></tr>
<tr><td>POST</td><td>/api/records</td><td>Create a record</td></tr>
<tr><td>PUT</td><td>/api/records/:id</td><td>Update a record (replaces all four fields)</td></tr>
<tr><td>DELETE</td><td>/api/records/:id</td><td>Delete a record</td></tr></table>

<h2>Fields</h2>
<table><tr><th>Field</th><th>Rule</th></tr>
<tr><td>id</td><td>Positive whole number, generated by the database. Not editable; ignored if sent.</td></tr>
<tr><td>title</td><td>Text, 3 to 80 characters</td></tr>
<tr><td>category</td><td>Text, 2 to 40 characters</td></tr>
<tr><td>description</td><td>Text, 5 to 300 characters</td></tr>
<tr><td>status</td><td>Exactly one of: <code>Pending</code>, <code>In progress</code>, <code>Completed</code></td></tr></table>

<h2>Request body (POST and PUT)</h2>
<p>Send <code>Content-Type: application/json</code> with all four editable fields and no id:</p>
<pre>${esc(sample)}</pre>

<h2>Responses</h2>
<table><tr><th>Request</th><th>Success</th><th>Status</th></tr>
<tr><td>GET all</td><td>Array of records, or []</td><td>200</td></tr>
<tr><td>GET one</td><td>One record including id</td><td>200</td></tr>
<tr><td>POST</td><td>Saved record with new id</td><td>201</td></tr>
<tr><td>PUT</td><td>Updated record with original id</td><td>200</td></tr>
<tr><td>DELETE</td><td><code>{"message":"Record deleted."}</code></td><td>200</td></tr></table>
<table><tr><th>Error</th><th>Status</th></tr>
<tr><td>Invalid input, invalid id or malformed JSON</td><td>400</td></tr>
<tr><td>Record or route not found</td><td>404</td></tr>
<tr><td>Database unavailable on /health</td><td>503</td></tr>
<tr><td>Unexpected server failure</td><td>500</td></tr></table>
<p>Every error is JSON, e.g. <code>{"message":"Title must have 3 to 80 characters."}</code></p>
</body></html>`;
};
